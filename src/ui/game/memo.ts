// The short memo of the rules as on PDF page 5 (docs/TZ.md, «Детали», п. 2). Numbers come from the game data.
import type { GameData } from '../../engine/types';

export interface MemoSection {
  title: string;
  lines: string[];
}

export function memo(data: GameData): MemoSection[] {
  const e = data.econ;
  const r = data.rules;
  return [
    {title:'Раунд',lines:['1. Море: откройте карту моря','2. Ход Пиратов','3. Ход Компании']},
    {title:'Ход команды: оба корабля сразу',lines:[`1. Трюм: +${e.income} Пороха (больше ${e.cap} не влезет). Горящие корабли получают урон.`,`2. Добор до ${r.hand} карт. Планы «Жемчужины» тоже считаются.`,'3. Действия: карт не больше Команды, один Залп на корабль.','4. «Ход окончен».']},
    {title:'Залп',lines:[`Стоит ${data.ships[0].volleyCost} Порох. Урон равен Пушкам, по диагонали на 1 меньше. Второй корабль по той же цели бьёт на ${r.jointBonus} сильнее (раз в ход). Без Заряда бьёт по Корпусу.`]},
    {title:'Ход противника',lines:['Реакций не больше, чем Парусов. Играйте их, когда враг объявил Залп или карту, до урона. Порох берите из своего Трюма.']},
    {title:'Свободные действия',lines:[`Продать карту: +${r.sellGain} Порох. Передать карту союзнику. Перестроение: ${r.regroupCost} Порох (Пиратам бесплатно, пока «Жемчужина» на плаву). Потушить Пожар: сбросить карту.`]},
    {title:'Урон',lines:['Шкала на минимуме: остаток урона идёт в Корпус. Команда не ниже 1. При Корпусе 0 корабль тонет.']},
    {title:'Корабль утонул',lines:['Капитан переходит к союзнику: 1 карта в свой ход и 1 Реакция в ход противника.']},
    {title:'Типы карт',lines:['ЗАРЯД · вместе с Залпом','ПРИКАЗ · в свой ход','РЕМОНТ · в свой ход','РЕАКЦИЯ · в ход противника']},
  ];
}

