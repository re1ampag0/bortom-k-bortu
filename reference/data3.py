BASE = {"ЗАРЯД": 1.0, "РЕАКЦИЯ": 1.5, "ПРИКАЗ": 2.0, "РЕМОНТ": 2.0}


def norm(card):
    return BASE[card["type"]] + card["cost"] + card.get("soul", 0) + (2 if card.get("legend") else 0)


def expanded_cards():
    out = []
    for ship in SHIPS:
        n = 0
        for card, count in DECKS[ship["code"]]:
            for _ in range(count):
                n += 1
                c = copy.deepcopy(card)
                c["deck"] = ship["code"]
                c["code"] = f"{ship['code']}-{n:02d}"
                out.append(c)
    return out


def legend_cards():
    out = []
    for ship in SHIPS:
        c = copy.deepcopy(LEGENDS[ship["code"]])
        c["deck"] = ship["code"]
        c["code"] = f"{ship['code']}-Л"
        out.append(c)
    return out


def sea_cards():
    return [dict(name=n, when=w, big=b, text=t, flavor=f, key=k, code=f"С-{i + 1:02d}", sea=True)
            for i, (n, w, b, t, f, k) in enumerate(SEA)]


def balance_rows():
    rows = []
    allc = expanded_cards()
    for ship in SHIPS:
        cards = [c for c in allc if c["deck"] == ship["code"]]
        cnt = {t: sum(1 for c in cards if c["type"] == t) for t in BASE}
        rows.append(dict(
            ship=ship, n=len(cards), uniq=len({c["name"] for c in cards}), cnt=cnt,
            val=sum(c["v"] for c in cards), norm=sum(norm(c) for c in cards),
            diff=sum(c["v"] for c in cards) - sum(norm(c) for c in cards),
            paid=sum(1 for c in cards if c["cost"] > 0),
            cost_sum=sum(c["cost"] for c in cards),
            tiers={k: sum(1 for c in cards if c["cost"] == k) for k in (0, 1, 2, 3)},
        ))
    return rows


